    private void EqualBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EqualBTNActionPerformed
        String firstText = firstNumberTextField.getText().trim();
        String secondText = secondNumberTextField.getText().trim();

        if (firstText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kindly enter the first number first!", "Error!", JOptionPane.ERROR_MESSAGE);
            firstNumberTextField.requestFocus();
            return;
        }

        if (operator.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an operator first!", "Error!", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (secondText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kindly enter the second number to continue!", "Error!", JOptionPane.ERROR_MESSAGE);
            secondNumberTextField.requestFocus();
            return;
        }

        try {
            double firstNumber = Double.parseDouble(firstText);
            double secondNumber = Double.parseDouble(secondText);
            double result = 0;

            if (operator.equals("+")) {
                result = firstNumber + secondNumber;
            } else if (operator.equals("-")) {
                result = firstNumber - secondNumber;
            } else if (operator.equals("*")) {
                result = firstNumber * secondNumber;
            } else if (operator.equals("/")) {
                if (secondNumber == 0) {
                    JOptionPane.showMessageDialog(this, "Cannot divide by zero!", "Error!", JOptionPane.ERROR_MESSAGE);
                    resultTextField.setText("");
                    return;
                }
                result = firstNumber / secondNumber;
            }

            resultTextField.setText(String.valueOf(result));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid Input, Kindly Enter Numbers Only", "Error!", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_EqualBTNActionPerformed

