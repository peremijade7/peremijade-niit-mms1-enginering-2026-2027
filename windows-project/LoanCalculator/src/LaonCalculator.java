    private void calculateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateBtnActionPerformed
        String amountText = loanAmountField.getText().trim();
        String durationText = durationField.getText().trim();

        if (amountText.isEmpty() || durationText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kindly enter both Loan Amount and Duration!", "Error!", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            double loanAmount = Double.parseDouble(amountText);
            int duration = Integer.parseInt(durationText);

            if (loanAmount <= 0 || duration <= 0) {
                JOptionPane.showMessageDialog(this, "Loan Amount and Duration must be greater than zero!", "Error!", JOptionPane.ERROR_MESSAGE);
                return;
            }

            DecimalFormat df = new DecimalFormat("#,##0.00");
            double monthlyPrincipal = loanAmount / duration;
            double remainingBalance = loanAmount;
            double totalInterest = 0;
            double totalRepayment = 0;

            textArea.setText("");
            textArea.append(String.format("%-8s %-15s %-15s %-18s\n", "MONTH", "AMOUNT", "INTEREST", "MONTHLY REPAYMENT"));

            for (int month = 1; month <= duration; month++) {
                double interest = remainingBalance * 0.015;
                double monthlyRepayment = monthlyPrincipal + interest;

                totalInterest += interest;
                totalRepayment += monthlyRepayment;
                remainingBalance -= monthlyPrincipal;

                textArea.append(String.format(
                        "%-8d %-15s %-15s %-18s\n",
                        month,
                        df.format(monthlyPrincipal),
                        df.format(interest),
                        df.format(monthlyRepayment)
                ));
            }

            totalRepaymentField.setText(df.format(totalRepayment));
            totalInterestField.setText(df.format(totalInterest));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Numbers only! Enter valid numbers for both Loan Amount and Loan Duration.", "Error!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_calculateBtnActionPerformed

