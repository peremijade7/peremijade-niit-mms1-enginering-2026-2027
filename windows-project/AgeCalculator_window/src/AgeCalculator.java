    private void calculateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateBtnActionPerformed
        String dayText = birthDayField.getText().trim();
        String monthText = birthMonthField.getText().trim();
        String yearText = birthYearField.getText().trim();

        if (dayText.isEmpty() || monthText.isEmpty() || yearText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kindly fill in Day, Month, and Year!", "Error!", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            int day = Integer.parseInt(dayText);
            int month = Integer.parseInt(monthText);
            int year = Integer.parseInt(yearText);

            LocalDate birthDate = LocalDate.of(year, month, day);
            LocalDate today = LocalDate.now();

            if (birthDate.isAfter(today)) {
                JOptionPane.showMessageDialog(this, "Birth date cannot be in the future!", "Error!", JOptionPane.ERROR_MESSAGE);
                return;
            }

            Period age = Period.between(birthDate, today);
            yearsField.setText(String.valueOf(age.getYears()));
            monthsField.setText(String.valueOf(age.getMonths()));
            daysField.setText(String.valueOf(age.getDays()));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Numbers only! Please enter valid numbers.", "Error!", JOptionPane.ERROR_MESSAGE);
        } catch (DateTimeException e) {
            JOptionPane.showMessageDialog(this, "Invalid calendar date! Check your Day, Month (1-12), or Year.", "Error!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_calculateBtnActionPerformed

