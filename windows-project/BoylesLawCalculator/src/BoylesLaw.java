    private void calculateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateBtnActionPerformed
        String choice = dropdownMenu.getSelectedItem().toString();

        if (choice.equals("Choose One...")) {
            JOptionPane.showMessageDialog(this, "Please select what to find first!", "Error!", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            double result = 0;

            if (choice.equals("Initial Pressure (P1)")) {
                String v1Text = v1TextField.getText().trim();
                String p2Text = p2TextField.getText().trim();
                String v2Text = v2TextField.getText().trim();
                if (v1Text.isEmpty() || p2Text.isEmpty() || v2Text.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Kindly fill in V1, P2, and V2!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                double v1 = Double.parseDouble(v1Text);
                double p2 = Double.parseDouble(p2Text);
                double v2 = Double.parseDouble(v2Text);
                if (v1 == 0) {
                    JOptionPane.showMessageDialog(this, "V1 cannot be zero!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                result = (p2 * v2) / v1;

            } else if (choice.equals("Initial Volume (V1)")) {
                String p1Text = p1TextField.getText().trim();
                String p2Text = p2TextField.getText().trim();
                String v2Text = v2TextField.getText().trim();
                if (p1Text.isEmpty() || p2Text.isEmpty() || v2Text.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Kindly fill in P1, P2, and V2!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                double p1 = Double.parseDouble(p1Text);
                double p2 = Double.parseDouble(p2Text);
                double v2 = Double.parseDouble(v2Text);
                if (p1 == 0) {
                    JOptionPane.showMessageDialog(this, "P1 cannot be zero!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                result = (p2 * v2) / p1;

            } else if (choice.equals("Final Pressure (P2)")) {
                String p1Text = p1TextField.getText().trim();
                String v1Text = v1TextField.getText().trim();
                String v2Text = v2TextField.getText().trim();
                if (p1Text.isEmpty() || v1Text.isEmpty() || v2Text.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Kindly fill in P1, V1, and V2!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                double p1 = Double.parseDouble(p1Text);
                double v1 = Double.parseDouble(v1Text);
                double v2 = Double.parseDouble(v2Text);
                if (v2 == 0) {
                    JOptionPane.showMessageDialog(this, "V2 cannot be zero!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                result = (p1 * v1) / v2;

            } else if (choice.equals("Final Volume (V2)")) {
                String p1Text = p1TextField.getText().trim();
                String v1Text = v1TextField.getText().trim();
                String p2Text = p2TextField.getText().trim();
                if (p1Text.isEmpty() || v1Text.isEmpty() || p2Text.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Kindly fill in P1, V1, and P2!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                double p1 = Double.parseDouble(p1Text);
                double v1 = Double.parseDouble(v1Text);
                double p2 = Double.parseDouble(p2Text);
                if (p2 == 0) {
                    JOptionPane.showMessageDialog(this, "P2 cannot be zero!", "Error!", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                result = (p1 * v1) / p2;
            }

            resultTextField.setText(String.valueOf(result));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid Input! Kindly enter numbers only.", "Error!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_calculateBtnActionPerformed

